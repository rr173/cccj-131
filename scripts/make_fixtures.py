#!/usr/bin/env python3
"""Write the reusable JSONL fixtures used by the drill and the docs.

Run: python3 scripts/make_fixtures.py
Everything is deterministic, so re-running rewrites identical bytes.

Files are written into fixtures/<scenario>/<step>-<kind>.jsonl.
"""

from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURES = os.path.join(ROOT, "fixtures")


def row(**kwargs):
    return json.dumps(kwargs, sort_keys=True)


def write(path, lines):
    full = os.path.join(FIXTURES, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    return full


# --------------------------------------------------------------------------- #
# main drill
# --------------------------------------------------------------------------- #
def main_drill():
    base = "main_drill"
    write(f"{base}/01_outbound.jsonl", [
        row(gateway_id="gw-main", delivery_id="D-100", attempt_id="att-1",
            recipient="Alice@Example.COM", queue_id="QUEUE-9",
            envelope_id="ENV-A", sent_at="2026-02-01T00:00:00Z"),
        # an unrelated recipient whose receipt never changes
        row(gateway_id="gw-main", delivery_id="D-200", attempt_id="att-1",
            recipient="bob@example.com", queue_id="QUEUE-B",
            envelope_id="ENV-B", sent_at="2026-02-01T00:00:00Z"),
    ])
    write(f"{base}/02_dsn.jsonl", [
        # domain case differs from the outbound row; local part is identical
        row(gateway_id="gw-main", report_id="RPT-1", item_id="ITEM-1",
            recipient="Alice@example.com", occurred_at="2026-02-01T01:00:00Z",
            action="delivered", queue_id="QUEUE-9"),
        row(gateway_id="gw-main", report_id="RPT-B", item_id="ITEM-B",
            recipient="bob@example.com", occurred_at="2026-02-01T01:30:00Z",
            action="failed", queue_id="QUEUE-B"),
    ])
    write(f"{base}/03_outbound_retry.jsonl", [
        row(gateway_id="gw-main", delivery_id="D-100", attempt_id="att-2",
            recipient="Alice@example.com", queue_id="QUEUE-9",
            envelope_id="ENV-B", sent_at="2026-02-01T00:10:00Z"),
    ])
    write(f"{base}/04_correction_withdraw.jsonl", [
        row(gateway_id="gw-main", report_id="RPT-1-COR1",
            item_id="ITEM-1-COR1", target_report_id="RPT-1",
            target_item_id="ITEM-1", occurred_at="2026-02-01T03:00:00Z",
            action="withdraw"),
    ])
    # the resolution file is generated by the CLI drill because it quotes the
    # live candidate fingerprint; a placeholder explains the shape
    write(f"{base}/05_resolution.template.jsonl", [
        row(gateway_id="gw-main", report_id="RPT-1", item_id="ITEM-1",
            delivery_id="D-100", attempt_id="att-2",
            recipient="Alice@example.com",
            candidate_fingerprint="<sha256 of the current candidate set>",
            decided_at="2026-02-01T02:00:00Z"),
    ])


# --------------------------------------------------------------------------- #
# feature matrix
# --------------------------------------------------------------------------- #
def feature_matrix():
    base = "matrix"
    write(f"{base}/empty_intersection_outbound.jsonl", [
        row(gateway_id="gwA", delivery_id="D1", attempt_id="a1",
            recipient="x@example.com", queue_id="Q1", envelope_id="E1",
            sent_at="2026-01-01T00:00:00Z"),
    ])
    write(f"{base}/empty_intersection_dsn.jsonl", [
        # queue matches, envelope does not: the intersection is empty
        row(gateway_id="gwA", report_id="R1", item_id="I1",
            recipient="x@example.com", occurred_at="2026-01-01T01:00:00Z",
            action="delivered", queue_id="Q1", envelope_id="OTHER"),
    ])
    write(f"{base}/two_gateways_outbound.jsonl", [
        row(gateway_id="gwA", delivery_id="D1", attempt_id="a1",
            recipient="x@example.com", queue_id="Q1", envelope_id="E1",
            sent_at="2026-01-01T00:00:00Z"),
        row(gateway_id="gwB", delivery_id="D1", attempt_id="a1",
            recipient="x@example.com", queue_id="Q1", envelope_id="E1",
            sent_at="2026-01-01T00:00:00Z"),
    ])
    write(f"{base}/two_gateways_dsn.jsonl", [
        # identical report/item numbers on two gateways are two identities
        row(gateway_id="gwA", report_id="R1", item_id="I1",
            recipient="x@example.com", occurred_at="2026-01-01T01:00:00Z",
            action="delivered", queue_id="Q1", envelope_id="E1"),
        row(gateway_id="gwB", report_id="R1", item_id="I1",
            recipient="x@example.com", occurred_at="2026-01-01T01:00:00Z",
            action="delivered", queue_id="Q1", envelope_id="E1"),
    ])
    write(f"{base}/terminals_outbound.jsonl", [
        row(gateway_id="g", delivery_id="D1", attempt_id="a1",
            recipient="u@example.com", queue_id="Q1",
            sent_at="2026-01-01T00:00:00Z"),
        row(gateway_id="g", delivery_id="D2", attempt_id="b1",
            recipient="u@example.com", queue_id="Q2",
            sent_at="2026-01-01T00:00:00Z"),
        row(gateway_id="g", delivery_id="D3", attempt_id="c1",
            recipient="u@example.com", queue_id="Q3",
            sent_at="2026-01-01T00:00:00Z"),
    ])
    write(f"{base}/terminals_dsn.jsonl", [
        row(gateway_id="g", report_id="R1", item_id="I1",
            recipient="u@example.com", occurred_at="2026-01-01T01:00:00Z",
            action="delivered", queue_id="Q1"),
        row(gateway_id="g", report_id="R2", item_id="I2",
            recipient="u@example.com", occurred_at="2026-01-01T01:10:00Z",
            action="failed", queue_id="Q1"),
        row(gateway_id="g", report_id="R3", item_id="I3",
            recipient="u@example.com", occurred_at="2026-01-01T01:20:00Z",
            action="delayed", queue_id="Q3"),
    ])
    # identical sent_at, ids that differ only lexicographically: "att-9" sorts
    # AFTER "att-10", so it is the delivery's chosen attempt
    write(f"{base}/retry_outbound.jsonl", [
        row(gateway_id="g", delivery_id="D4", attempt_id="att-10",
            recipient="u@example.com", queue_id="Q4", envelope_id="E10",
            sent_at="2026-01-01T00:00:00Z"),
        row(gateway_id="g", delivery_id="D4", attempt_id="att-9",
            recipient="u@example.com", queue_id="Q4", envelope_id="E9",
            sent_at="2026-01-01T00:00:00Z"),
    ])
    # the receipt names envelope E10, so it proves att-10 only; the delivery
    # still reports att-9 (awaiting) because ordering is raw lexicographic
    write(f"{base}/retry_dsn.jsonl", [
        row(gateway_id="g", report_id="R4", item_id="I4",
            recipient="u@example.com", occurred_at="2026-01-01T01:00:00Z",
            action="delivered", queue_id="Q4", envelope_id="E10"),
    ])
    write(f"{base}/domain_case_outbound.jsonl", [
        row(gateway_id="g", delivery_id="D5", attempt_id="a1",
            recipient="Case@Example.com", queue_id="Q5",
            sent_at="2026-01-01T00:00:00Z"),
    ])
    write(f"{base}/domain_case_dsn.jsonl", [
        row(gateway_id="g", report_id="R5", item_id="I5",
            recipient="Case@EXAMPLE.COM", occurred_at="2026-01-01T01:00:00Z",
            action="delivered", queue_id="Q5"),
        # a different local part is a different recipient
        row(gateway_id="g", report_id="R6", item_id="I6",
            recipient="case@example.com", occurred_at="2026-01-01T01:00:00Z",
            action="delivered", queue_id="Q5"),
    ])
    write(f"{base}/correction_conflict_dsn.jsonl", [
        row(gateway_id="g", report_id="R7", item_id="I7",
            recipient="u@example.com", occurred_at="2026-01-01T01:00:00Z",
            action="delivered", queue_id="Q7"),
    ])
    write(f"{base}/correction_conflict_outbound.jsonl", [
        row(gateway_id="g", delivery_id="D7", attempt_id="a1",
            recipient="u@example.com", queue_id="Q7",
            sent_at="2026-01-01T00:00:00Z"),
    ])
    write(f"{base}/correction_conflict_corrections.jsonl", [
        row(gateway_id="g", report_id="C7a", item_id="CI7a",
            target_report_id="R7", target_item_id="I7",
            occurred_at="2026-01-01T02:00:00Z", action="failed"),
        row(gateway_id="g", report_id="C7b", item_id="CI7b",
            target_report_id="R7", target_item_id="I7",
            occurred_at="2026-01-01T03:00:00Z", action="delayed"),
    ])


# --------------------------------------------------------------------------- #
# out-of-order corrections
# --------------------------------------------------------------------------- #
def late_corrections():
    base = "late_corrections"
    write(f"{base}/01_outbound.jsonl", [
        row(gateway_id="g", delivery_id="D1", attempt_id="a1",
            recipient="u@example.com", queue_id="Q",
            sent_at="2026-01-01T00:00:00Z"),
    ])
    write(f"{base}/02_correction_before_original.jsonl", [
        row(gateway_id="g", report_id="C2", item_id="CI2",
            target_report_id="C1", target_item_id="CI1",
            occurred_at="2026-01-01T04:00:00Z", action="failed"),
        row(gateway_id="g", report_id="C1", item_id="CI1",
            target_report_id="R1", target_item_id="I1",
            occurred_at="2026-01-01T03:00:00Z", action="delivered"),
    ])
    write(f"{base}/03_original.jsonl", [
        row(gateway_id="g", report_id="R1", item_id="I1",
            recipient="u@example.com", occurred_at="2026-01-01T01:00:00Z",
            action="delivered", queue_id="Q"),
    ])


def main():
    main_drill()
    feature_matrix()
    late_corrections()
    count = sum(len(files) for _, _, files in os.walk(FIXTURES))
    print(f"wrote {count} fixture files under {FIXTURES}")


if __name__ == "__main__":
    main()
